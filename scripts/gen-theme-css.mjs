/**
 * Generates global.css and theme/tailwind-colors.js from theme/palette.json.
 * palette.json is the single source of truth for colour; run `npm run theme` after editing.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const palette = JSON.parse(readFileSync(resolve(root, 'theme/palette.json'), 'utf8'));

const NAMES = {
  canvas: 'canvas', surface: 'surface', surfaceRaised: 'surface-raised',
  surfaceSunken: 'surface-sunken', surfaceGlass: 'glass', overlay: 'overlay', scrim: 'scrim',

  text: 'ink', textSecondary: 'ink-secondary', textTertiary: 'ink-tertiary',
  textStrong: 'ink-strong',
  textDisabled: 'ink-disabled', textPlaceholder: 'ink-placeholder',
  textInverse: 'ink-inverse', textLink: 'link',
  textOnAccent: 'on-accent',

  borderSubtle: 'edge-subtle', border: 'edge', borderStrong: 'edge-strong',
  borderInput: 'edge-input', borderFocus: 'edge-focus',

  brandPearl: 'brand-pearl', brandBlush: 'brand-blush', brandLavender: 'brand-lavender',
  brandLavenderShadow: 'brand-lavender-shadow', brandPurple: 'brand-purple',
  brandPurpleFn: 'brand-purple-fn', brandViolet: 'brand-violet',
  brandCandy: 'brand-candy', brandChrome: 'brand-chrome',

  accent: 'accent', accentStrong: 'accent-strong', accentSoft: 'accent-soft',
  accentOn: 'accent-on',

  successFg: 'success', successBg: 'success-bg', successBorder: 'success-edge',
  successSolid: 'success-solid', successOn: 'success-on',
  warningFg: 'warning', warningBg: 'warning-bg', warningBorder: 'warning-edge',
  warningSolid: 'warning-solid', warningOn: 'warning-on',
  errorFg: 'error', errorBg: 'error-bg', errorBorder: 'error-edge',
  errorSolid: 'error-solid', errorOn: 'error-on',
  infoFg: 'info', infoBg: 'info-bg', infoBorder: 'info-edge',
  infoSolid: 'info-solid', infoOn: 'info-on',

  disabledBg: 'disabled-bg', disabledFg: 'disabled', disabledBorder: 'disabled-edge',
  pressed: 'pressed', hover: 'hover', selected: 'selected', skeleton: 'skeleton',

  bubbleUser: 'bubble-user', bubbleAi: 'bubble-ai', bubbleBorder: 'bubble-edge',
  tabBar: 'tab-bar', tabActive: 'tab-active', tabInactive: 'tab-inactive',
};

const rgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

const keys = Object.keys(palette.light);
const missing = keys.filter((k) => !NAMES[k]);
if (missing.length) throw new Error('No Tailwind name for: ' + missing.join(', '));
const extra = Object.keys(palette.dark).filter((k) => !keys.includes(k));
if (extra.length) throw new Error('Dark has keys light does not: ' + extra.join(', '));

const vars = (mode) =>
  keys.map((k) => `    --color-${NAMES[k]}: ${rgb(palette[mode][k])};`).join('\n');

const css = `/* GENERATED by scripts/gen-theme-css.mjs — do not edit.
   Edit theme/palette.json, then run: npm run theme */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
${vars('light')}
  }

  .dark:root {
${vars('dark')}
  }
}
`;
writeFileSync(resolve(root, 'global.css'), css);

const colors = keys
  .map((k) => `  '${NAMES[k]}': 'rgb(var(--color-${NAMES[k]}) / <alpha-value>)',`)
  .join('\n');

writeFileSync(
  resolve(root, 'theme/tailwind-colors.js'),
  `// GENERATED by scripts/gen-theme-css.mjs — do not edit.\nmodule.exports = {\n${colors}\n};\n`,
);

console.log(`theme: wrote ${keys.length} colours to global.css and theme/tailwind-colors.js`);
