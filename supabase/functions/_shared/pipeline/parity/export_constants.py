#!/usr/bin/env python3
"""Export the Python pipeline's constants to JSON for the TypeScript port.

Mode instructions, the planner prompt, routing patterns, banned phrases and
checks are taken from the Python modules themselves, so the port cannot drift
from them by a retyped character. Re-run after any change to those modules:

    python3 supabase/functions/_shared/pipeline/parity/export_constants.py \\
        --base "/path/to/AI APP"

Writes ../constants.json. The knowledge base, style card and her style_rules.json
are NOT exported here: they live in the database (kb schema).
"""
import argparse
import json
import os
import re
import sys


def rx(p):
    return {"pattern": p.pattern, "i": bool(p.flags & re.I), "m": bool(p.flags & re.M)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    args = ap.parse_args()
    os.environ["SAOHLIN_BASE"] = args.base
    sys.path.insert(0, os.path.join(args.base, "scripts"))
    import response_modes as rm
    import stage10_voice_score as s10
    import stage6_retrieval_eval as s6
    import stage8_chat as s8
    import voice_checks_v2 as vc

    out = {
        "_about": "Generated by parity/export_constants.py from the Python pipeline. Do not edit by hand.",
        "modes": {
            "MODES": {k: {"label": v["label"], "budget": list(v["budget"]), "instruction": v["instruction"]}
                      for k, v in rm.MODES.items()},
            "DEFAULT_MODE": rm.DEFAULT_MODE,
            "RETRIEVAL": {k: list(v) for k, v in rm.RETRIEVAL.items()},
            "PHASE2": {k: list(v) for k, v in rm.PHASE2.items()},
            "RETRIEVED_TOKEN_BUDGET": rm.RETRIEVED_TOKEN_BUDGET,
            "CHARS_PER_TOKEN": rm.CHARS_PER_TOKEN,
            "PINNED": rm.PINNED,
            "IDENTITY": rx(rm._IDENTITY), "SAFETY": rx(rm._SAFETY), "CRISIS": rx(rm._CRISIS),
            "PAUSE": rx(rm._PAUSE), "DEFINITION": rx(rm._DEFINITION), "CARD": rx(rm._CARD),
            "EXISTENTIAL": rx(rm._EXISTENTIAL), "NOT_WORKING": rx(rm._NOT_WORKING),
            "PLANNER_SYSTEM": rm.PLANNER_SYSTEM,
            "UNDERSTANDING_KEYS": list(rm.UNDERSTANDING_KEYS),
            "RE_BEHAVIOUR": rx(rm._RE_BEHAVIOUR), "RE_REPEAT": rx(rm._RE_REPEAT),
            "RE_UNDERNEATH": rx(rm._RE_UNDERNEATH),
            "STOP": sorted(rm._STOP),
            "TIC_WORDS": rm.TIC_WORDS,
        },
        "checks": {
            "SENT": rx(vc.SENT),
            "FORBIDDEN_WORDS": [{"label": w["label"], "pattern": w["pattern"], "use_instead": w["use_instead"]}
                                for w in vc.FORBIDDEN_WORDS],
            "FORBIDDEN_CLICHES": [list(c) for c in vc.FORBIDDEN_CLICHES],
            "STEP_LIST": rx(vc._STEP_LIST), "PAUSE_TOPIC": rx(vc._PAUSE_TOPIC),
            "SECULARISED": rx(vc._SECULARISED),
            "FORBIDDEN_OPENERS": [list(c) for c in vc.FORBIDDEN_OPENERS],
            "CLICHES_EXEMPT_IN_KARTA": sorted(vc.CLICHES_EXEMPT_IN_KARTA),
            "BLAME_OTHER": rx(vc._BLAME_OTHER), "SELF_INQUIRY": rx(vc._SELF_INQUIRY),
        },
        "score": {
            "SENT": rx(s10.SENT),
            "TY_PRON": rx(s10.TY_PRON), "VY_PRON": rx(s10.VY_PRON),
            "TY_VERB": rx(s10.TY_VERB), "VY_VERB": rx(s10.VY_VERB),
            "TY_STOP": sorted(s10.TY_STOP), "VY_STOP": sorted(s10.VY_STOP),
            "PROTECTED": s10.PROTECTED, "STEP_LIST": rx(s10.STEP_LIST),
        },
        "chat": {
            "OVERRIDES": s8.OVERRIDES,
            "ALWAYS_RULES": s8.ALWAYS_RULES,
            "N_KNOWLEDGE": s8.N_KNOWLEDGE, "N_VIDEO": s8.N_VIDEO, "N_RULES": s8.N_RULES,
            "N_EXEMPLARS": s8.N_EXEMPLARS, "RRF_K": s8.RRF_K, "FUSE_DEPTH": s8.FUSE_DEPTH,
            "EXEMPLAR_EXCLUDING_RULES": list(s8.EXEMPLAR_EXCLUDING_RULES),
        },
        "bm25": {"STOP": sorted(s6.STOP), "STEM_LEN": s6.STEM_LEN},
    }
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "constants.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
